"""Export the approved SetTrace identity to Android launcher resources.

Run from any directory with Python 3 and Pillow:
    python tool/generate_android_icons.py

The final SVG/PNG in docs/design/current-ui/assets/brand remain the source of truth.
Adaptive foregrounds use a 108 dp canvas with the 100-unit brand artwork fitted
to the central 72 dp visible area, so launcher masks preserve the design scale.
"""

from pathlib import Path
import hashlib
import json
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "docs/design/current-ui/assets/brand"
RES = ROOT / "android/app/src/main/res"
SVG_NS = {"svg": "http://www.w3.org/2000/svg"}
DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def write_resource(relative_path, content):
    target = RES / relative_path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8", newline="\n")


def main():
    foreground_source = BRAND / "logo/settrace-symbol-white.svg"
    foreground = ET.parse(foreground_source).getroot()
    paths = [element.attrib["d"] for element in foreground.findall("svg:path", SVG_NS)]
    if len(paths) != 4:
        raise ValueError("Expected the four closed capsules of the final three-track design")
    background_source = BRAND / "settrace-icon/layers/01-background.svg"
    background = ET.parse(background_source).find("svg:rect", SVG_NS).attrib["fill"]

    vector_paths = "\n".join(
        f'        <path android:fillColor="#FFFFFF" android:pathData="{data}" />'
        for data in paths
    )
    write_resource("drawable/ic_launcher_foreground.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_android_icons.py from the final SVG master.
     100 units -> 72 dp visible artwork, centered in the 108 dp adaptive canvas. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:scaleX="0.72"
        android:scaleY="0.72"
        android:translateX="18"
        android:translateY="18">
{vector_paths}
    </group>
</vector>
''')
    write_resource("values/ic_launcher_colors.xml", f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from the final SetTrace brand background. -->
<resources>
    <color name="ic_launcher_background">{background}</color>
</resources>
''')

    for version in (26, 33):
        monochrome = ('    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
                      if version >= 33 else '')
        adaptive = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_android_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
{monochrome}</adaptive-icon>
'''
        for name in ("ic_launcher", "ic_launcher_round"):
            write_resource(f"mipmap-anydpi-v{version}/{name}.xml", adaptive)

    # Legacy Android uses the approved rounded preview directly, without adding
    # adaptive padding. Round launchers receive an explicit circular fallback.
    rounded = Image.open(BRAND / "settrace-icon/settrace-icon.preview.png").convert("RGBA")
    square = Image.open(BRAND / "settrace-icon/settrace-icon.png").convert("RGBA")
    mask = Image.new("L", square.size, 0)
    ImageDraw.Draw(mask).ellipse((0, 0, square.width - 1, square.height - 1), fill=255)
    circular = square.copy()
    circular.putalpha(mask)
    for density, size in DENSITIES.items():
        directory = RES / f"mipmap-{density}"
        directory.mkdir(parents=True, exist_ok=True)
        rounded.resize((size, size), Image.Resampling.LANCZOS).save(directory / "ic_launcher.png")
        circular.resize((size, size), Image.Resampling.LANCZOS).save(directory / "ic_launcher_round.png")
        # The old density-specific foregrounds are replaced by the shared vector.
        obsolete = directory / "ic_launcher_foreground.png"
        if obsolete.is_file():
            obsolete.unlink()

    source_hash = hashlib.sha256(foreground_source.read_bytes()).hexdigest()
    print(json.dumps({
        "source": str(foreground_source.relative_to(ROOT)),
        "source_sha256": source_hash,
        "background": background,
        "legacy_sizes": DENSITIES,
        "adaptive": {"viewport_dp": 108, "visible_dp": 72, "scale": 0.72, "inset_dp": 18},
        "themed_icon_min_api": 33,
    }, indent=2))


if __name__ == "__main__":
    main()
